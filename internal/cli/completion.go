package cli

import (
	"bytes"
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"
)

const bashCompletionFallback = `# Zacman fallback for environments without bash-completion.
# The Cobra-generated script calls _get_comp_words_by_ref; provide the small
# subset Zacman needs when the bash-completion package has not been sourced.
if ! declare -F _get_comp_words_by_ref >/dev/null 2>&1; then
  _get_comp_words_by_ref() {
    local prev_index
    while (($#)); do
      case "$1" in
        -n)
          # Word-break characters are ignored because COMP_WORDS already gives
          # us the tokenized words and Zacman's completion does not parse key=value.
          shift 2
          ;;
        cur)
          cur="${COMP_WORDS[COMP_CWORD]}"
          shift
          ;;
        prev)
          if (( COMP_CWORD > 0 )); then
            prev_index=$((COMP_CWORD - 1))
            prev="${COMP_WORDS[prev_index]}"
          else
            prev=""
          fi
          shift
          ;;
        words)
          words=("${COMP_WORDS[@]}")
          shift
          ;;
        cword)
          cword="$COMP_CWORD"
          shift
          ;;
        *)
          shift
          ;;
      esac
    done
  }
fi
`

func newCompletionCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:                   "completion <bash|zsh|fish|powershell>",
		Short:                 "Generate shell completion scripts",
		Long:                  completionHelp(),
		Args:                  cobra.ExactValidArgs(1),
		ValidArgs:             []string{"bash", "zsh", "fish", "powershell"},
		DisableFlagsInUseLine: true,
		RunE: func(cmd *cobra.Command, args []string) error {
			noDescriptions, _ := cmd.Flags().GetBool("no-descriptions")
			return writeCompletion(cmd.Root(), args[0], noDescriptions, cmd.OutOrStdout())
		},
	}
	cmd.Flags().Bool("no-descriptions", false, "Omit descriptions from completion candidates")
	return cmd
}

func writeCompletion(root *cobra.Command, shell string, noDescriptions bool, out io.Writer) error {
	switch shell {
	case "bash":
		var generated bytes.Buffer
		if err := root.GenBashCompletionV2(&generated, !noDescriptions); err != nil {
			return err
		}
		script, err := makeBashCompletionSelfContained(generated.String())
		if err != nil {
			return err
		}
		_, err = io.WriteString(out, script)
		return err
	case "zsh":
		if noDescriptions {
			return root.GenZshCompletionNoDesc(out)
		}
		return root.GenZshCompletion(out)
	case "fish":
		return root.GenFishCompletion(out, !noDescriptions)
	case "powershell":
		if noDescriptions {
			return root.GenPowerShellCompletion(out)
		}
		return root.GenPowerShellCompletionWithDesc(out)
	default:
		return fmt.Errorf("unsupported completion shell %q (choose bash, zsh, fish, or powershell)", shell)
	}
}

func makeBashCompletionSelfContained(script string) (string, error) {
	const marker = "__zacman_init_completion()\n{"
	if strings.Contains(script, "if ! declare -F _get_comp_words_by_ref") {
		return script, nil
	}
	if !strings.Contains(script, marker) {
		return "", fmt.Errorf("could not make Bash completion self-contained: Cobra output format changed")
	}
	return strings.Replace(script, marker, bashCompletionFallback+"\n"+marker, 1), nil
}

func completionHelp() string {
	return `Generate Zacman command, flag, package, and systemd-unit completions.

Bash (self-contained; no bash-completion package required):
  mkdir -p ~/.local/share/zacman/completions
  zacman completion bash > ~/.local/share/zacman/completions/zacman.bash
  echo '[[ -r "$HOME/.local/share/zacman/completions/zacman.bash" ]] && source "$HOME/.local/share/zacman/completions/zacman.bash"' >> ~/.bashrc
  source ~/.bashrc

Zsh:
  mkdir -p ~/.zsh/completions
  zacman completion zsh > ~/.zsh/completions/_zacman
  Add fpath=("$HOME/.zsh/completions" $fpath) to ~/.zshrc before Oh My Zsh initializes completion, then restart Zsh.

Fish:
  mkdir -p ~/.config/fish/completions
  zacman completion fish > ~/.config/fish/completions/zacman.fish

PowerShell:
  zacman completion powershell > "$HOME/zacman-completion.ps1"
  Dot-source that file from your PowerShell profile.

Use ` + "`zacman completion <shell> --no-descriptions`" + ` to omit descriptions.`
}
